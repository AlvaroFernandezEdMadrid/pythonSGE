class Colores():
    def __init__(self):
        self.azulClaro="#A6DFE9"
        self.azulOscuro="#73CEDF"
        self.blanco="#FFFFFF"
        self.negro="#171717"
        self.prueba="#4D4D4D"

    def getAzulOscuro(self):
        return self.azulOscuro

    def getAzulClaro(self):
        return self.azulClaro

    def getBlanco(self):
        return self.blanco
    
    def getNegro(self):
        return self.negro
    
    def getPrueba(self):
        return self.prueba
    